#!/usr/bin/env python3
"""Generate /etc/keyd/default.conf: Super as the macOS Command key.

    python3 gen-default.py > default.conf && sudo keyd check default.conf
    sudo install -m644 default.conf /etc/keyd/default.conf && sudo keyd reload
"""
import string

# Super keeps H (hide), M (minimise) and D (show desktop) for the shell; every
# other letter, the digits and the zoom keys become Command shortcuts.
LETTERS = [c for c in string.ascii_lowercase if c not in 'hmd']
KEYS = LETTERS + list('1234567890') + ['minus', 'equal']
# Every key the composites must pass through untouched: [control] (in
# macos-ctrl) binds all letters, so a composite that leaves one out lets
# [control] rewrite it -- Ctrl+Super+D became Super+Delete.
PASS = list(string.ascii_lowercase) + list('1234567890') + ['minus', 'equal']

HEADER = """# macOS-style Command key: Super+<key> sends Ctrl+<key> to applications.
# Generated by config/keyd/gen-default.py in yet-another-gnomintosh -- edit that, not this.
#
# A key bound in a modifier layer is emitted without that layer's modifier, so
# [meta] c = C-c delivers a clean Ctrl+C. Keys left unbound (h, m, d, Tab,
# Space, arrows) reach the shell as Super, untouched.
#
# The composites below are load-bearing. keyd resolves a key in the most
# recently activated layer that binds it, and a composite wins only for keys
# it binds itself. So [meta+shift] must bind the digits -- or Super+Shift+3/4/5
# (screenshots) fall through to [meta] and arrive as Ctrl+Shift+3 -- and the
# [control]/[alt] composites must bind every key they are to leave alone, or
# Ctrl+Super+Q (lock) becomes Ctrl+Q.
#
# Panic: Backspace+Escape+Enter terminates keyd.

[ids]
*

[main]
"""

out = [HEADER, "[meta]"] + [f"{k} = C-{k}" for k in KEYS]
out += ["", "[meta+shift]"] + [f"{k} = C-S-{k}" for k in LETTERS]
# Shift+Super+<digit> is the shell's (screenshots), so it passes through.
out += [f"{k} = S-M-{k}" for k in KEYS if k not in LETTERS]
for combo, mods in [("control+meta", "C-M-"), ("alt+meta", "A-M-"),
                    ("control+meta+shift", "C-M-S-"), ("alt+meta+shift", "A-M-S-")]:
    out += ["", f"[{combo}]"] + [f"{k} = {mods}{k}" for k in PASS]
out += ["", "# macOS-style Control; switched by macos-ctrl",
        "include macos-ctrl"]
print("\n".join(out))
